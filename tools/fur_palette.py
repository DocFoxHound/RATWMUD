#!/usr/bin/env python3
"""The painted wolves' palette: one list of fur and eye colours for the server, central's identity check and the client.

  python3 tools/fur_palette.py           regenerate the C++ and client tables from Data/Wolves/palette.json
  python3 tools/fur_palette.py --check   fail if a generated table is out of date

Docs/Design/81-painted-wolves.md. The palette's rule is kept here: earthy, natural, muted. A fur colour whose strongest
and weakest channel are more than 100 apart, or an eye colour more than 160, is refused.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'Data/Wolves/palette.json'
CPP = ROOT / 'Core/RatwFurPalette.inc'
CLIENT_TS = ROOT / 'Client/src/ui/furPalette.generated.ts'
HEADER = 'Generated by tools/fur_palette.py from Data/Wolves/palette.json. Do not edit.'
FUR_SPREAD, EYE_SPREAD = 100, 160


class PaletteError(ValueError):
    pass


def _check(ok, message):
    if not ok:
        raise PaletteError(message)


def spread(hex_colour: str) -> int:
    channels = [int(hex_colour[i:i + 2], 16) for i in (1, 3, 5)]
    return max(channels) - min(channels)


def load(path: Path = SOURCE) -> dict:
    """The palette, checked; raises PaletteError when the file is unsound."""
    data = json.loads(path.read_text(encoding='utf-8'))
    _check(data.get('format') == 'ratw-fur-palette' and data.get('version') == 1, 'Not a version 1 fur palette.')
    for kind, limit in (('fur', FUR_SPREAD), ('eyes', EYE_SPREAD)):
        seen = set()
        for c in data[kind]:
            _check(re.fullmatch(r'[a-z][a-z_]{0,15}', c['id']) is not None, f'{c["id"]!r}: an id is 1-16 lower-case letters and underscores.')
            _check(c['id'] not in seen, f'{c["id"]!r}: duplicate id.')
            seen.add(c['id'])
            _check(isinstance(c['name'], str) and 0 < len(c['name']) <= 24 and '"' not in c['name'] and '\\' not in c['name'], f'{c["id"]!r}: a name is 1-24 characters.')
            _check(re.fullmatch(r'#[0-9a-f]{6}', c['hex']) is not None, f'{c["id"]!r}: a colour is #rrggbb, lower case.')
            _check(spread(c['hex']) <= limit, f'{c["id"]!r}: too strong a colour for a wolf ({spread(c["hex"])} > {limit}): mute it.')
            if kind == 'fur':
                _check(isinstance(c.get('group'), str) and c['group'], f'{c["id"]!r}: a fur colour has a group.')
    zones = [z['id'] for z in data['zones']]
    _check(len(zones) == len(set(zones)) and 0 < len(zones) <= 15 and all(re.fullmatch(r'[a-z][a-z_]{0,15}', z) for z in zones),
           'Zones are up to 15 different ids (the zone maps keep one in four bits).')
    fur, eyes = {c['id'] for c in data['fur']}, {c['id'] for c in data['eyes']}
    seen = set()
    for coat in data['coats']:
        _check(coat['id'] not in seen and re.fullmatch(r'[a-z][a-z_]{0,15}', coat['id']) is not None, f'coat {coat["id"]!r}: a new id.')
        seen.add(coat['id'])
        _check(len(coat['coat']) == 3 and set(coat['coat']) <= fur and coat['eyes'] in eyes, f'coat {coat["id"]!r}: three fur ids and an eye id.')
        for zone, ids in coat.get('zones', {}).items():
            _check(zone in zones and len(ids) == 3 and set(ids) <= fur, f'coat {coat["id"]!r}: zone {zone!r} is three fur ids.')
    return data


def cpp_table(data: dict) -> str:
    lines = [f'// {HEADER}', '// RATW_FUR(id, name, rgb)  RATW_EYE(id, name, rgb)  RATW_FUR_ZONE(id, name)']
    lines += [f'RATW_FUR("{c["id"]}", "{c["name"]}", 0x{c["hex"][1:]})' for c in data['fur']]
    lines += [f'RATW_EYE("{c["id"]}", "{c["name"]}", 0x{c["hex"][1:]})' for c in data['eyes']]
    lines += [f'RATW_FUR_ZONE("{z["id"]}", "{z["name"]}")' for z in data['zones']]
    return '\n'.join(lines) + '\n'


def client_table(data: dict) -> str:
    def rows(items, keys):
        return '\n'.join('    {' + ', '.join(f'{k}: {json.dumps(i[k], ensure_ascii=False)}' for k in keys if k in i) + '},' for i in items)
    return (f'// {HEADER}\n'
            'export interface FurColour { id: string; name: string; group: string; hex: string }\n'
            'export interface EyeColour { id: string; name: string; hex: string }\n'
            'export interface ReadyCoat { id: string; name: string; coat: string[]; eyes: string; zones?: Record<string, string[]> }\n\n'
            f'export const FurColours: readonly FurColour[] = [\n{rows(data["fur"], ("id", "name", "group", "hex"))}\n];\n\n'
            f'export const EyeColours: readonly EyeColour[] = [\n{rows(data["eyes"], ("id", "name", "hex"))}\n];\n\n'
            '/** The fur zones, in the order the zone maps number them (tools/avatar_prep.py). */\n'
            f'export const FurZones: readonly {{id: string; name: string}}[] = [\n{rows(data["zones"], ("id", "name"))}\n];\n\n'
            f'export const ReadyCoats: readonly ReadyCoat[] = [\n{rows(data["coats"], ("id", "name", "coat", "eyes", "zones"))}\n];\n')


def main() -> int:
    try:
        data = load()
    except (PaletteError, KeyError, TypeError, json.JSONDecodeError) as error:
        print(f'Data/Wolves/palette.json: {error}', file=sys.stderr)
        return 1
    stale = []
    for path, text in ((CPP, cpp_table(data)), (CLIENT_TS, client_table(data))):
        if '--check' in sys.argv[1:]:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(path)
        else:
            path.write_text(text, encoding='utf-8')
    for path in stale:
        print(f'{path.relative_to(ROOT)} is out of date: run python3 tools/fur_palette.py', file=sys.stderr)
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
